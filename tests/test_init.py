def test_init_validates_before_it_writes(tmp_path: Path, monkeypatch: pytest.MonkeyPatch) -> None:
    """If the guard rail fails, no half-written agent directory is left behind."""

    def refuse(_path: Path) -> None:
        raise ManifestError("nope")

    monkeypatch.setattr(init_agent, "load_manifest", refuse)

    with pytest.raises(RiggingError):
        _run(tmp_path, ["x", "", "", "", "", "-", "-", "-", "-", "-", "-", "", "", "", "", "-", "y"])
    assert not (tmp_path / "agents").exists()


def test_init_summary_shows_the_gate_and_the_limits(tmp_path: Path) -> None:
    answers = ["ops", "", "", "", "", "refund_order", "-", "-", "-", "-", "-", "1", "3", "1000", "0", "-", "y"]
    code, output, _ = _run(tmp_path, answers)

    assert code == 0
    assert "approval  auto_deny · gate on refund_order" in output
    assert "limits    steps=3 tokens=1000 usd=0.0" in output


def test_init_yaml_round_trips_as_a_mapping(tmp_path: Path) -> None:
    code, _, _ = _run(tmp_path, ["r", "", "", "", "", "-", "-", "-", "-", "-", "-", "", "", "", "", "-", "y"])
    assert code == 0

    raw = yaml.safe_load((tmp_path / "agents" / "r" / "agent.yaml").read_text())
    assert isinstance(raw, dict)
    assert raw["name"] == "r"


def test_init_cli_wires_the_flags_and_exits_2_on_refusal(tmp_path: Path) -> None:
    from rigging.cli import main

    assert main(["init", "--yes", "--dir", str(tmp_path / "agents")]) == 0
    manifest = tmp_path / "agents" / "my-agent" / "agent.yaml"
    assert load_manifest(manifest).name == "my-agent"

    # same command again: the existing directory is a refusal, not an overwrite
    assert main(["init", "--yes", "--dir", str(tmp_path / "agents")]) == 2
    assert main(["init", "--yes", "--force", "--dir", str(tmp_path / "agents")]) == 0
