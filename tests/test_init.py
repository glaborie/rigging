"""`harness init`: the interview writes a manifest the loader accepts.

The prompt callable is injected in every test, so the interview runs with no
terminal and no sleeping on stdin — the same reason `CLIPromptApproval` takes one.
"""

from __future__ import annotations

import io
from collections.abc import Callable, Iterator, Sequence
from pathlib import Path

import pytest
import yaml

from rigging import init_agent
from rigging.errors import ManifestError, RiggingError
from rigging.init_agent import InitError, run_init
from rigging.manifest import load_manifest


def _scripted(answers: Sequence[str]) -> tuple[Callable[[str], str], list[str]]:
    """Answers in order, and the list of prompts seen (to assert on the interview)."""
    it: Iterator[str] = iter(answers)
    seen: list[str] = []

    def ask(prompt: str) -> str:
        seen.append(prompt)
        try:
            return next(it)
        except StopIteration:  # a question the test did not expect
            raise AssertionError(f"unexpected prompt: {prompt!r}") from None

    return ask, seen


def _run(tmp_path: Path, answers: Sequence[str]) -> tuple[int, str, list[str]]:
    ask, seen = _scripted(answers)
    out = io.StringIO()
    code = run_init(directory=tmp_path / "agents", ask=ask, out=out)
    return code, out.getvalue(), seen


def test_init_writes_a_manifest_the_loader_accepts(tmp_path: Path) -> None:
    answers = [
        "refunds",                      # name
        "Handles refund requests.",     # description
        "2",                            # model: qwen3:8b
        "1",                            # credential_profile: ollama
        "2",                            # system prompt: tool-using
        "lookup_order,refund_order",    # tools, by name
        "-",                            # retriever: none
        "",                             # on_input: suggested
        "",                             # on_tool_call: suggested
        "",                             # on_tool_result: suggested
        "",                             # on_output: suggested
        "1",                            # approval: auto_deny
        "",                             # max_steps: default
        "",                             # max_tokens: default
        "",                             # max_cost_usd: default
        "-",                            # exporters: none
        "y",                            # write?
    ]
    code, output, _ = _run(tmp_path, answers)

    assert code == 0
    manifest = tmp_path / "agents" / "refunds" / "agent.yaml"
    prompt = tmp_path / "agents" / "refunds" / "prompt.md"
    assert manifest.exists() and prompt.exists()

    spec = load_manifest(manifest)  # the real validator, not a re-implementation
    assert spec.name == "refunds"
    assert spec.model == "qwen3:8b"
    assert spec.tools == ["lookup_order", "refund_order"]
    assert spec.retriever is None
    assert spec.approval.policy == "auto_deny"
    assert spec.guardrails.on_input[0].name == "pii_redaction"
    assert spec.limits.max_steps == 20
    assert prompt.read_text().startswith("You are a careful support agent")
    assert spec.prompt().startswith("You are a careful support agent")
    assert "wrote" in output


def test_init_derives_the_approval_gate_from_tool_metadata(tmp_path: Path) -> None:
    """`side_effecting_tools` comes from the registry, not from the operator."""
    answers = ["ops", "", "", "", "", "current_time,refund_order", "-",
               "-", "-", "-", "-", "2", "", "", "", "-", "y"]
    code, _, _ = _run(tmp_path, answers)

    assert code == 0
    spec = load_manifest(tmp_path / "agents" / "ops" / "agent.yaml")
    assert spec.approval.side_effecting_tools == ["refund_order"]
    assert spec.approval.policy == "cli"
    assert spec.guardrails.on_input == []  # every hook answered "-"
    assert spec.guardrails.on_output == []


def test_init_generated_file_carries_the_schema_comment(tmp_path: Path) -> None:
    code, _, _ = _run(tmp_path, ["a", "", "", "", "", "-", "-", "-", "-", "-", "-", "", "", "", "", "-", "y"])

    assert code == 0
    text = (tmp_path / "agents" / "a" / "agent.yaml").read_text()
    assert text.startswith("# Generated by `harness init`")
    assert "yaml-language-server: $schema=" in text
    assert "agent.schema.json" in text
    # A real `$schema:` key would be rejected by the schema (additionalProperties: false).
    assert "\n$schema:" not in text


def test_init_yes_takes_every_default_without_asking(tmp_path: Path) -> None:
    def never(_prompt: str) -> str:  # pragma: no cover - must not be called
        raise AssertionError("--yes asked a question")

    out = io.StringIO()
    code = run_init(directory=tmp_path / "agents", assume_yes=True, ask=never, out=out)

    assert code == 0
    spec = load_manifest(tmp_path / "agents" / "my-agent" / "agent.yaml")
    assert (spec.name, spec.model, spec.tools) == ("my-agent", "beam:cloud", [])
    assert spec.approval.policy == "auto_deny"


def test_init_refuses_to_overwrite_without_force(tmp_path: Path) -> None:
    answers = ["dup", "", "", "", "", "-", "-", "-", "-", "-", "-", "", "", "", "", "-", "y"]
    assert _run(tmp_path, answers)[0] == 0

    ask, _ = _scripted(answers)
    with pytest.raises(InitError, match="--force"):
        run_init(directory=tmp_path / "agents", ask=ask, out=io.StringIO())  # type: ignore[arg-type]


def test_init_force_overwrites(tmp_path: Path) -> None:
    answers = ["dup", "", "", "", "", "-", "-", "-", "-", "-", "-", "", "", "", "", "-", "y"]
    _run(tmp_path, answers)

    ask, _ = _scripted(["dup", "second pass", "", "", "", "-", "-", "-", "-", "-", "-", "", "", "", "", "-", "y"])
    code = run_init(directory=tmp_path / "agents", force=True, ask=ask, out=io.StringIO())  # type: ignore[arg-type]

    assert code == 0
    spec = load_manifest(tmp_path / "agents" / "dup" / "agent.yaml")
    assert spec.description == "second pass"


def test_init_declining_the_last_question_writes_nothing(tmp_path: Path) -> None:
    answers = ["nope", "", "", "", "", "-", "-", "-", "-", "-", "-", "", "", "", "", "-", "n"]
    ask, _ = _scripted(answers)

    with pytest.raises(InitError, match="nothing written"):
        run_init(directory=tmp_path / "agents", ask=ask, out=io.StringIO())  # type: ignore[arg-type]

    assert not (tmp_path / "agents").exists()


